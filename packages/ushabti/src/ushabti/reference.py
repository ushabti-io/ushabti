"""Generates the spell.yaml reference from the Spell model.

``docs/spells.md`` is the output of this module, and a test fails when the two
differ. Regenerate it after changing a model::

    uv run python -m ushabti.reference > docs/spells.md
"""

import inspect
import re
import sys
import types
from datetime import timedelta
from enum import Enum
from pathlib import Path
from typing import Annotated, Any, Literal, Union, get_args, get_origin

import annotated_types
from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from ushabti._base import StrictModel, format_duration
from ushabti.implements import builtin_implements
from ushabti.maat import Comparison
from ushabti.spell import SecretReference, Spell

_INTRO = """\
<!-- Generated by `uv run python -m ushabti.reference`. Do not edit by hand. -->

# spell.yaml reference

A spell is the declarative definition of one ushabti (one agent instance): its
role, its instructions, its model, the fields (targets) it tends, the implements
(tools) it may use, its Ma'at (the desired state), and the policy for the weighing
(the safety gate every write implement must pass).

This page is generated from the `Spell` model in the `ushabti` package, so it
cannot drift from what the loader accepts. Two complete examples live in
[examples/spells](../examples/spells): [k3s-watcher.yaml](../examples/spells/k3s-watcher.yaml)
and [proxmox-watcher.yaml](../examples/spells/proxmox-watcher.yaml).

Check a spell before you run it:

```bash
ushabti check-spell path/to/spell.yaml
```

The loader rejects three things outright: a key it does not know, an implement
that is not registered, and a secret written into the file.
"""

_ENVIRONMENT = """\
## Environment references and secrets

Any string in a spell may hold an environment reference written `${NAME}`. The
reference is kept as written when the spell is loaded and is resolved only when
the value is needed, so `check-spell` works on a machine that does not hold the
secrets. An unset or empty variable counts as not set.

A key named like a secret may only hold a single environment reference, never a
literal value. A key counts as a secret when one of its words is `token`,
`password`, `passwd`, `secret`, `key`, or `apikey`. So `api_key`, `apiKey`, and
`admin_token` are secrets, and `max_tokens` is not. This applies everywhere in
the file, including the arguments of an `observe` block.

```yaml
api_key: ${ANTHROPIC_API_KEY}   # accepted
api_key: sk-live-123            # rejected: a literal secret
```

`check-spell` prints the resolved spell with every secret masked, and warns
about each referenced variable that is not set.
"""

_MAAT = """\
## How Ma'at is evaluated

An assertion with only an `id` and a `description` is context for the model: it
is never evaluated. Add `observe` and `expect` to have the vigil (the monitoring
loop) check it on every tick:

1. The vigil runs the read implement named in `observe`.
2. It looks up `expect.path` in the result and applies the comparison.
3. When `expect` does not hold, it raises isfet (something is wrong now).
4. When `expect` holds and `omen` also holds, it raises an omen (something will
   be wrong soon).

Isfet and omens each raise one summons (a unit of work) when they first appear,
not one per tick. When the path is missing or the values cannot be compared,
the result is unknown and nothing is raised.
"""


def spell_reference() -> str:
    """The whole reference as Markdown."""
    paths = _collect(Spell, "")
    parts = [_INTRO, "## Keys\n"]
    for model, where in paths.items():
        parts.append(_section(model, where, paths))
    parts += [_COMPARISONS(), _MAAT, _ENVIRONMENT, _implements()]
    return "\n".join(part.rstrip("\n") + "\n" for part in parts)


def _collect(model: type[BaseModel], path: str) -> dict[type[BaseModel], list[str]]:
    """Every model reachable from ``model``, with the paths it is found at."""
    found: dict[type[BaseModel], list[str]] = {model: [path]}
    for name, field in model.model_fields.items():
        key = field.alias or name
        for nested, is_list in _nested_models(field.annotation):
            child = f"{path}.{key}" if path else key
            child += "[]" if is_list else ""
            for inner, where in _collect(nested, child).items():
                found.setdefault(inner, []).extend(
                    p for p in where if p not in found.get(inner, [])
                )
    return found


def _nested_models(annotation: Any) -> list[tuple[type[BaseModel], bool]]:
    """The spell models inside an annotation, and whether each sits in a list."""
    if inspect.isclass(annotation) and issubclass(annotation, StrictModel):
        return [(annotation, False)]
    origin = get_origin(annotation)
    if origin is tuple:
        return [(model, True) for model, _ in _nested_models(get_args(annotation)[0])]
    if origin in (Union, types.UnionType):
        return [found for arg in get_args(annotation) for found in _nested_models(arg)]
    return []


def _section(
    model: type[BaseModel], where: list[str], paths: dict[type[BaseModel], list[str]]
) -> str:
    heading = " and ".join(f"`{path}`" for path in where) if where[0] else "Top level"
    lines = [f"### {heading}", ""]
    doc = inspect.getdoc(model) if model.__doc__ else None
    if doc:
        lines += [" ".join(doc.split()), ""]
    lines += ["| Key | Type | Default | Description |", "|---|---|---|---|"]
    for name, field in model.model_fields.items():
        key = field.alias or name
        description = " ".join((field.description or "").split())
        row = (f"`{key}`", _type(field, paths), _default(field), description)
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    return "\n".join(lines) + "\n"


def _type(field: FieldInfo, paths: dict[type[BaseModel], list[str]]) -> str:
    return _label(field.annotation, paths) + _bounds(field.metadata)


def _bounds(metadata: Any) -> str:
    """Numeric limits attached to a type, in words."""
    text = ""
    for constraint in metadata:
        if isinstance(constraint, annotated_types.Gt):
            text += f", greater than {constraint.gt}"
        elif isinstance(constraint, annotated_types.Ge):
            text += f", at least {constraint.ge}"
    return text


def _label(annotation: Any, paths: dict[type[BaseModel], list[str]]) -> str:
    if annotation == SecretReference:
        return "environment reference such as `${NAME}`"
    origin = get_origin(annotation)
    if origin is Annotated:
        base, *metadata = get_args(annotation)
        return _label(base, paths) + _bounds(metadata)
    if origin in (Union, types.UnionType):
        options = [arg for arg in get_args(annotation) if arg is not type(None)]
        if len(options) == 1:
            return _label(options[0], paths)
        if set(options) == {str, int, float, bool}:
            return "string, number, boolean, or null"
        return " or ".join(_label(option, paths) for option in options)
    if origin is tuple:
        item = _label(get_args(annotation)[0], paths)
        return f"list of {item.replace('map', 'maps', 1) if item.startswith('map') else item + 's'}"
    if origin is dict:
        return "map"
    if origin is Literal:
        return " or ".join(f"`{value}`" for value in get_args(annotation))
    if inspect.isclass(annotation):
        if issubclass(annotation, StrictModel):
            where = paths[annotation]
            return f"map, see [{_plain(where)}](#{_slug(_heading(where))})"
        if issubclass(annotation, Enum):
            return "one of " + ", ".join(f"`{member.value}`" for member in annotation)
        if issubclass(annotation, bool):
            return "boolean"
        if issubclass(annotation, int):
            return "integer"
        if issubclass(annotation, float):
            return "number"
        if issubclass(annotation, str):
            return "string"
        if issubclass(annotation, timedelta):
            return "duration such as `500ms`, `60s`, `5m`, `1h`"
        if issubclass(annotation, Path):
            return "path"
    return "any JSON value"


def _default(field: FieldInfo) -> str:
    if field.default_factory is not None:
        return "`{}`"
    value = field.default
    if value is PydanticUndefined:
        return "**required**"
    if value is None:
        return "none"
    if isinstance(value, BaseModel):
        return "see its section"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, Enum):
        return f"`{value.value}`"
    if isinstance(value, timedelta):
        return f"`{format_duration(value)}`"
    if isinstance(value, tuple):
        return "`[" + ", ".join(str(item) for item in value) + "]`"
    if value == "":
        return "empty"
    return f"`{value}`"


def _heading(where: list[str]) -> str:
    return " and ".join(f"`{path}`" for path in where)


def _plain(where: list[str]) -> str:
    return " and ".join(f"`{path}`" for path in where)


def _slug(heading: str) -> str:
    """The anchor GitHub gives a heading."""
    kept = re.sub(r"[^\w\- ]", "", heading.lower())
    return kept.replace(" ", "-")


def _COMPARISONS() -> str:  # noqa: N802  (reads as a section, like the constants above)
    meaning = {
        Comparison.EQ: "equal to",
        Comparison.NE: "not equal to",
        Comparison.LT: "less than",
        Comparison.LE: "less than or equal to",
        Comparison.GT: "greater than",
        Comparison.GE: "greater than or equal to",
    }
    lines = [
        "## Comparisons",
        "",
        "The `op` of an `expect` or `omen` condition is one of:",
        "",
        "| `op` | The condition holds when the observed value is |",
        "|---|---|",
    ]
    lines += [f"| `{op.value}` | {meaning[op]} `value` |" for op in Comparison]
    lines += [
        "",
        "`eq` and `ne` compare any JSON value. The ordering comparisons need two",
        "numbers or two strings. A boolean never equals a number, so `true` is not `1`.",
    ]
    return "\n".join(lines) + "\n"


def _implements() -> str:
    lines = [
        "## Implements",
        "",
        "These are the implements that ship with the `ushabti` package. A spell may",
        "list any of them under `spec.implements`. Every implement is either `read`",
        "or `write`, and a write implement only runs with a `PASS` verdict from the",
        "weighing.",
        "",
        "| Implement | Kind | What it does | Status |",
        "|---|---|---|---|",
    ]
    for implement in builtin_implements():
        source = inspect.getsource(type(implement)._run)
        status = "scaffold stub, not implemented yet" if "TODO(scaffold)" in source else "ready"
        cells = (f"`{implement.name}`", f"`{implement.kind.value}`", implement.description, status)
        lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "There is no shell implement."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":  # pragma: no cover
    sys.stdout.write(spell_reference())
